// Assembles the deployable project:
//   1. fills legal/*.txt with the operator data from config.local.json and writes
//      tgcloud/lib/generated.js (texts, app URL, admin ids) for the bot modules;
//   2. unless --no-app: builds ww3-sv as a static export and copies it to app/, with the legal
//      pages added as app/legal/<page>.html.
// `npm run deploy` runs this and then `tgcloud push`.

import { execSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PAGES, fillText, renderHtml } from './legal-render.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const configPath = join(root, 'config.local.json');
if (!existsSync(configPath)) {
  console.error('config.local.json is missing: copy config.example.json and fill in the operator data.');
  process.exit(1);
}
const config = JSON.parse(readFileSync(configPath, 'utf8'));
const appUrl = (config.appUrl ?? '').replace(/\/$/, '');

const texts = Object.fromEntries(
  Object.keys(PAGES).map((page) => [page, fillText(readFileSync(join(root, 'legal', `${page}.txt`), 'utf8'), config)]),
);

writeFileSync(join(root, 'tgcloud/lib/generated.js'), `// Generated by scripts/build.mjs from config.local.json and legal/*.txt. Do not edit or commit.

export const APP_URL = ${JSON.stringify(appUrl)};
export const ADMIN_IDS = ${JSON.stringify(config.adminIds ?? [])};
export const OPERATOR = ${JSON.stringify({ name: config.operator.name, email: config.operator.email })};
export const TEXTS = ${JSON.stringify(texts, null, 2)};
`);
console.log('wrote tgcloud/lib/generated.js');

if (!process.argv.includes('--no-app')) {
  const gameDir = resolve(root, config.gameDir ?? '../../ww3-sv');
  console.log(`building the game in ${gameDir}`);
  execSync('bun run build:static', { cwd: gameDir, stdio: 'inherit' });

  const app = join(root, 'app');
  rmSync(app, { recursive: true, force: true });
  cpSync(join(gameDir, 'build'), app, { recursive: true });
  mkdirSync(join(app, 'legal'), { recursive: true });
  for (const [page, text] of Object.entries(texts)) {
    writeFileSync(join(app, 'legal', `${page}.html`), renderHtml(page, text));
  }
  console.log('assembled app/ (game + legal pages)');
}
