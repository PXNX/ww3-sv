"""
PostgreSQL access: one async connection pool, the schema (created on start, additions only), and
small helpers. Times are unix seconds in bigint columns, as the game and the Bot API count them.

The ledger never deletes. Balances are sums: revivals bought (purchases) plus those earned by
inviting friends (referrals) minus those spent (spends). A purchase is keyed by Telegram's unique
charge id, so a duplicate delivery of the same payment grants nothing.
"""
import time
from contextlib import asynccontextmanager
from typing import Any, Final

from psycopg import AsyncConnection
from psycopg.rows import dict_row
from psycopg_pool import AsyncConnectionPool

SCHEMA: Final[str] = """
CREATE TABLE IF NOT EXISTS accounts (
    user_id bigint PRIMARY KEY,
    username text,
    first_name text,
    -- 'de' or 'en' after the Telegram language, for messages the player did not ask for
    language text,
    first_seen bigint DEFAULT extract(epoch FROM now())::bigint,
    -- Unix seconds until which Pro is active, or null
    pro_until bigint
);

-- The express consent to immediate delivery and the acknowledged loss of the right of withdrawal
-- (§ 356 Abs. 4 and 5 BGB), one row per user and version of the legal texts
CREATE TABLE IF NOT EXISTS consents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    version text NOT NULL,
    source text NOT NULL,
    created_at bigint DEFAULT extract(epoch FROM now())::bigint,
    UNIQUE (user_id, version)
);

-- An invoice we issued; its id is the invoice payload, so a payment can be matched to one user and
-- one sku without trusting anything the client sends
CREATE TABLE IF NOT EXISTS invoices (
    id text PRIMARY KEY,
    user_id bigint NOT NULL,
    sku text NOT NULL,
    stars integer NOT NULL,
    created_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_invoices_user_created ON invoices (user_id, created_at);

CREATE TABLE IF NOT EXISTS purchases (
    charge_id text PRIMARY KEY,
    provider_charge_id text,
    user_id bigint NOT NULL,
    sku text NOT NULL,
    stars integer NOT NULL,
    invoice_id text NOT NULL,
    -- What this payment granted, so the grant and the booking are one insert
    revives integer NOT NULL DEFAULT 0,
    recurring boolean NOT NULL DEFAULT false,
    created_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_purchases_user ON purchases (user_id);

CREATE TABLE IF NOT EXISTS spends (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    revives integer NOT NULL,
    reason text NOT NULL,
    created_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_spends_user ON spends (user_id);

-- The daily-reward streak as the game last reported it, for the reminder two hours before it ends.
-- The streak itself lives in the game; this is only its deadline, so the bot can warn in time.
CREATE TABLE IF NOT EXISTS streaks (
    user_id bigint PRIMARY KEY,
    streak integer NOT NULL,
    -- When the streak breaks (the player's local midnight), or null without a streak
    expires_at bigint,
    -- The deadline a reminder was already sent for, so each deadline gets at most one
    reminded_for bigint NOT NULL DEFAULT 0,
    language text NOT NULL DEFAULT 'en',
    muted boolean NOT NULL DEFAULT false,
    -- Telegram refused the message (bot never started or blocked); cleared when the player writes
    -- to the bot or allows messages in the Mini App
    blocked boolean NOT NULL DEFAULT false,
    updated_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_streaks_expires ON streaks (expires_at);

-- Who invited whom with their invite link; one row per invited player
CREATE TABLE IF NOT EXISTS referrals (
    invitee_id bigint PRIMARY KEY,
    referrer_id bigint NOT NULL,
    revives integer NOT NULL,
    created_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_referrals_referrer ON referrals (referrer_id);

-- Friends, one row per direction: made whenever someone starts the bot through a player's invite
-- link, whether or not that earned a reward (an invitee who already played, or one past the cap)
CREATE TABLE IF NOT EXISTS friendships (
    user_id bigint NOT NULL,
    friend_id bigint NOT NULL,
    created_at bigint NOT NULL,
    PRIMARY KEY (user_id, friend_id)
);
-- Invites from before friendships were kept are friendships too
INSERT INTO friendships (user_id, friend_id, created_at)
SELECT referrer_id, invitee_id, created_at FROM referrals
UNION ALL SELECT invitee_id, referrer_id, created_at FROM referrals
ON CONFLICT DO NOTHING;

-- A press on a game message's Play button. The id is in the game page's URL and comes back with
-- every score; it is the only proof of who plays (a game page has no Mini App initData), so it is
-- long and random. Sessions older than a day are deleted when the next one is opened.
CREATE TABLE IF NOT EXISTS game_sessions (
    id text PRIMARY KEY,
    user_id bigint NOT NULL,
    first_name text,
    language text,
    -- The game's short name at @BotFather, which is the mode id in the game
    game text NOT NULL,
    chat_id bigint NOT NULL,
    message_id bigint NOT NULL,
    created_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_game_sessions_created ON game_sessions (created_at);

-- Each player's best per game and chat, as it was set on Telegram's scoreboard; a copy, so /top can
-- list a chat's leaderboard and the bot can tell when someone takes the chat's record
CREATE TABLE IF NOT EXISTS group_scores (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id bigint NOT NULL,
    game text NOT NULL,
    user_id bigint NOT NULL,
    first_name text NOT NULL,
    score bigint NOT NULL,
    updated_at bigint NOT NULL,
    UNIQUE (chat_id, game, user_id)
);
CREATE INDEX IF NOT EXISTS idx_group_scores_chat_game_score ON group_scores (chat_id, game, score);

-- Player versus player (docs/rivals-api.md). Each player's latest published Beachhead base, with what
-- a raid could take (the part the bunker does not protect) and until when a raid shield holds
CREATE TABLE IF NOT EXISTS beachhead_bases (
    user_id bigint PRIMARY KEY,
    base jsonb NOT NULL,
    level integer NOT NULL DEFAULT 1,
    wood bigint NOT NULL DEFAULT 0,
    stone bigint NOT NULL DEFAULT 0,
    iron bigint NOT NULL DEFAULT 0,
    gold bigint NOT NULL DEFAULT 0,
    shielded_until bigint NOT NULL DEFAULT 0,
    updated_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_beachhead_bases_level ON beachhead_bases (level);

-- One attack: opened with the base and loot locked, settled once ('won', 'lost', or 'abandoned' when
-- the attacker opened another); outcome is null while open. Settled ones are the raid log.
CREATE TABLE IF NOT EXISTS beachhead_attacks (
    id text PRIMARY KEY,
    attacker_id bigint NOT NULL,
    target_id bigint NOT NULL,
    base jsonb NOT NULL,
    -- Quoted when opened; after a win, what was actually taken
    loot jsonb NOT NULL,
    revenge boolean NOT NULL DEFAULT false,
    outcome text,
    created_at bigint NOT NULL,
    settled_at bigint
);
CREATE INDEX IF NOT EXISTS idx_beachhead_attacks_attacker ON beachhead_attacks (attacker_id, target_id, settled_at);
CREATE INDEX IF NOT EXISTS idx_beachhead_attacks_target ON beachhead_attacks (target_id, settled_at);
CREATE INDEX IF NOT EXISTS idx_beachhead_attacks_created ON beachhead_attacks (created_at);

-- Each player's Hermit Hackers rig: a made-up address that belongs to the first who published it
CREATE TABLE IF NOT EXISTS hacker_rigs (
    user_id bigint PRIMARY KEY,
    ip text NOT NULL UNIQUE,
    bank bigint NOT NULL DEFAULT 0,
    firewall integer NOT NULL DEFAULT 1,
    hacks integer NOT NULL DEFAULT 0,
    look jsonb,
    shielded_until bigint NOT NULL DEFAULT 0,
    updated_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_hacker_rigs_updated ON hacker_rigs (updated_at);

-- One hack, like a Beachhead attack; settled ones are the target's firewall log, with the address
-- the attacker's rig had at the time
CREATE TABLE IF NOT EXISTS hacker_hacks (
    id text PRIMARY KEY,
    attacker_id bigint NOT NULL,
    target_id bigint NOT NULL,
    attacker_ip text NOT NULL,
    revenge boolean NOT NULL DEFAULT false,
    stolen bigint NOT NULL DEFAULT 0,
    outcome text,
    created_at bigint NOT NULL,
    settled_at bigint
);
CREATE INDEX IF NOT EXISTS idx_hacker_hacks_attacker ON hacker_hacks (attacker_id, target_id, settled_at);
CREATE INDEX IF NOT EXISTS idx_hacker_hacks_target ON hacker_hacks (target_id, settled_at);
CREATE INDEX IF NOT EXISTS idx_hacker_hacks_created ON hacker_hacks (created_at);
"""

_pool: AsyncConnectionPool | None = None


def now() -> int:
    return int(time.time())


async def open_pool(url: str) -> None:
    """Opens the pool and creates the tables that are missing."""
    global _pool
    _pool = AsyncConnectionPool(
        url, min_size=1, max_size=5, open=False, kwargs={"autocommit": True, "row_factory": dict_row}
    )
    await _pool.open(wait=True)
    async with _pool.connection() as conn:
        await conn.execute(SCHEMA)


async def close_pool() -> None:
    global _pool
    if _pool is not None:
        await _pool.close()
        _pool = None


@asynccontextmanager
async def connection():
    if _pool is None:
        raise RuntimeError("the database is not open")
    async with _pool.connection() as conn:
        yield conn


@asynccontextmanager
async def transaction(lock: int | None = None):
    """A transaction; with `lock`, it holds an advisory lock on that id (a user) until it ends."""
    async with connection() as conn:
        async with conn.transaction():
            if lock is not None:
                await conn.execute("SELECT pg_advisory_xact_lock(%s)", (lock,))
            yield conn


async def fetchone(query: str, params: tuple | dict = (), conn: AsyncConnection | None = None) -> dict[str, Any] | None:
    if conn is not None:
        return await (await conn.execute(query, params)).fetchone()
    async with connection() as own:
        return await (await own.execute(query, params)).fetchone()


async def fetchall(query: str, params: tuple | dict = (), conn: AsyncConnection | None = None) -> list[dict[str, Any]]:
    if conn is not None:
        return await (await conn.execute(query, params)).fetchall()
    async with connection() as own:
        return await (await own.execute(query, params)).fetchall()


async def execute(query: str, params: tuple | dict = (), conn: AsyncConnection | None = None) -> int:
    """Runs a statement; returns the number of rows it changed."""
    if conn is not None:
        return (await conn.execute(query, params)).rowcount
    async with connection() as own:
        return (await own.execute(query, params)).rowcount
